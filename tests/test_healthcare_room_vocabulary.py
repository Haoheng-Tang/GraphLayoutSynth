# --- Default essential generated mix --------------------------------------------


def test_default_generation_produces_essential_mix_only():
    config = load_config(DEFAULT_CONFIG_PATH)
    result = generate_candidate(seed=42, config=config)

    assert result.is_valid
    type_counts = Counter(
        attrs.get("type") for _, attrs in result.graph.nodes(data=True)
    )
    generated_types = set(type_counts)
    assert ESSENTIAL_GENERATED_TYPES <= generated_types
    # Optional types are allowed but not generated by the default grammar.
    assert not OPTIONAL_ROOM_TYPES & generated_types
    # Legacy types are no longer generated by default.
    assert "Corridor" not in generated_types
    assert "ClinicalSupport" not in generated_types

    assert type_counts["OnStageCorridor"] == 4
    assert type_counts["OffStageCorridor"] == 1
    assert type_counts["NurseStation"] == 2
    assert type_counts["Stair"] == 2
    assert 20 <= type_counts["PatientRoom"] <= 24


def test_default_generation_balances_patients_across_nurse_stations():
    config = load_config(DEFAULT_CONFIG_PATH)
    result = generate_candidate(seed=42, config=config)

    nurse_loads = Counter()
    for left, right, attrs in result.graph.edges(data=True):
        if attrs.get("edge_type") != "door":
            continue
        types = {
            left: result.graph.nodes[left].get("type"),
            right: result.graph.nodes[right].get("type"),
        }
        if set(types.values()) == {"PatientRoom", "NurseStation"}:
            nurse = left if types[left] == "NurseStation" else right
            nurse_loads[nurse] += 1

    assert sum(nurse_loads.values()) >= 20
    assert all(load <= 12 for load in nurse_loads.values())


