def _propose_from_instructions(tmp_path, monkeypatch, proposed_config: dict):
    monkeypatch.setenv(ENABLE_LLM_VARIANTS_ENV, "true")
    monkeypatch.setenv(LLM_VARIANT_DIR_ENV, str(tmp_path / "llm-variants"))
    monkeypatch.setenv("ANTHROPIC_API_KEY", "test-key")
    monkeypatch.setattr(
        assistant,
        "propose_grammar_variant_with_claude",
        lambda prompt, model, max_tokens: (
            "Rationale.\n```yaml\n" + yaml.safe_dump(proposed_config, sort_keys=False) + "\n```"
        ),
    )
    client = TestClient(create_app())
    return client.post(
        "/grammar-variants/propose-from-instructions",
        json={"instructionText": "# Rules\n\n- Add a kitchen and dining wing.\n"},
    )


def test_instruction_variant_with_new_canonical_types_validates(tmp_path, monkeypatch):
    proposed = _raw_config()
    # Extend the service zone with optional room types from the vocabulary.
    service_rule = next(
        rule for rule in proposed["grammar_rules"] if rule["name"] == "expand_service_zone"
    )
    service_rule["action"]["create_nodes"].append(
        {
            "alias": "kitchen",
            "type": "Kitchen",
            "count": 1,
            "attributes": {"is_abstract": False},
        }
    )
    service_rule["action"]["create_edges"].append(
        {
            "source": "kitchen",
            "target": "offstage",
            "edge_type": "door",
            "mode": "each_to_one",
        }
    )

    response = _propose_from_instructions(tmp_path, monkeypatch, proposed)

    assert response.status_code == 200
    assert response.json()["valid"] is True


def test_instruction_variant_with_misspelled_type_fails_validation(tmp_path, monkeypatch):
    proposed = _raw_config()
    service_rule = next(
        rule for rule in proposed["grammar_rules"] if rule["name"] == "expand_service_zone"
    )
    service_rule["action"]["create_nodes"].append(
        {
            "alias": "kitchen",
            "type": "Kichen",
            "count": 1,
            "attributes": {"is_abstract": False},
        }
    )

    response = _propose_from_instructions(tmp_path, monkeypatch, proposed)

    assert response.status_code == 200
    payload = response.json()
    assert payload["valid"] is False
    assert payload["status"] == "proposed_invalid"


